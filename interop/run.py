#!/usr/bin/env python3
"""XRouter <-> TheNet X1J interop run.

Starts the tnc2-emu container (TheNet X1J) and an XRouter container on a
private docker network, with XRouter dialling the emulator's KISS port as
a TCP KISS interface. Then it drives both consoles through the checks
below and saves raw transcripts and logs under the output directory.

  1. TheNet signs on, PARMS / MODE / NODES / ROUTES answer.
  2. TheNet sends NODES broadcasts (seen in the emulator's monitor log).
  3. XRouter lists TheNet as a neighbour (ROUTES) and a node (NODES).
  4. TheNet lists XRouter in NODES.
  5. AX.25 level 2 connect from XRouter to TheNet's callsign gets the
     TheNet prompt.
  6. NET/ROM connect from XRouter to TheNet's alias works.
  7. NET/ROM connect from TheNet's console to XRouter works.
  8. Level 2 downlink from TheNet's console to XRouter's PMS.

Usage: interop/run.py [--xrouter-tag 505o] [--image tnc2-emu:dev] [--out DIR]

Containers, network and volumes are all named tnc2-*, and only those are
removed at the end.
"""

from __future__ import annotations

import argparse
import datetime
import os
import re
import socket
import subprocess
import sys
import time

NET = "tnc2-net"
SUBNET = "172.29.73.0/24"
TN_IP = "172.29.73.10"
XR_IP = "172.29.73.11"

TN_CALL, TN_ALIAS = "G9TNT-1", "TNET"
XR_CALL, XR_ALIAS = "G9XRT", "XRNODE"
# XRouter's PMS callsign. With PMSQUAL at its default of 0 it is not in
# NODES broadcasts, so TheNet has to reach it with a plain level 2 downlink.
XR_PMSCALL = "G9XRT-2"
LOGIN_CALL = "G9ABC"

IAC, DONT, DO, WONT, WILL, SB, SE = 255, 254, 253, 252, 251, 250, 240

XROUTER_CFG = f"""# XRouter side of the TheNet X1J interop run (generated by interop/run.py).
# Comment lines must start in column 1.
NODECALL={XR_CALL}
NODEALIAS={XR_ALIAS}
CONSOLECALL={XR_CALL}
PMSCALL={XR_PMSCALL}
TELNETPORT=23
LOCATOR=IO91WL
IPADDRESS={XR_IP}
NODESINTERVAL=1
IDLETIME=900

CTEXT
{XR_CALL} XRouter interop node for TheNet X1J
***

# The TNC-2 emulator's radio port, as KISS over TCP. XRouter is the client.
INTERFACE=1
    TYPE=TCP
    ID=TheNet TNC2 KISS
    PROTOCOL=KISS
    MTU=256
    IOADDR={TN_IP}
    INTNUM=8001
ENDINTERFACE

PORT=1
    ID=TNC2 radio channel
    INTERFACENUM=1
    CHANNEL=A
    QUALITY=192
    MAXFRAME=2
    PACLEN=120
    FRACK=8000
    RESPTIME=1500
    RETRIES=10
ENDPORT
"""

ACCESS_SYS = "# Test harness only: any valid callsign may log in on telnet.\n0.0.0.0/0 1\n"


def sh(*args, check=True, capture=False):
    r = subprocess.run(args, check=False, capture_output=capture, text=True)
    if check and r.returncode != 0:
        raise RuntimeError(f"{' '.join(args)} failed: {r.stderr if capture else r.returncode}")
    return r


class Console:
    def __init__(self, name: str, host: str, port: int, log):
        self.name = name
        self.log = log
        deadline = time.time() + 30
        while True:
            try:
                self.sock = socket.create_connection((host, port), timeout=5)
                break
            except OSError:
                if time.time() > deadline:
                    raise
                time.sleep(1)
        self.sock.settimeout(0.2)
        self.buf = ""
        self.closed = False

    def _pump(self) -> bool:
        try:
            data = self.sock.recv(4096)
        except (socket.timeout, BlockingIOError):
            return False
        if not data:
            if not self.closed:
                self.log.write(f"\n[{now()} {self.name} closed the connection]\n")
            self.closed = True
            time.sleep(0.2)
            return False
        out = bytearray()
        i = 0
        while i < len(data):
            b = data[i]
            if b == IAC and i + 1 < len(data):
                cmd = data[i + 1]
                if cmd in (DO, DONT, WILL, WONT) and i + 2 < len(data):
                    opt = data[i + 2]
                    if cmd == DO:
                        self.sock.sendall(bytes([IAC, WONT, opt]))
                    elif cmd == WILL:
                        self.sock.sendall(bytes([IAC, DONT, opt]))
                    i += 3
                    continue
                if cmd == SB:
                    end = data.find(bytes([IAC, SE]), i)
                    i = len(data) if end < 0 else end + 2
                    continue
                i += 2
                continue
            out.append(b)
            i += 1
        text = out.decode("latin-1").replace("\r\n", "\n").replace("\r", "\n")
        self.buf += text
        self.log.write(text)
        self.log.flush()
        return True

    def send_raw(self, b: bytes, note: str):
        self.log.write(f"\n[{now()} >>> {note}]\n")
        self.sock.sendall(b)

    def send(self, line: str):
        self.send_raw(line.encode("latin-1") + b"\r", line)

    def expect(self, pattern: str, timeout: float = 10.0) -> str:
        rx = re.compile(pattern, re.I | re.M)
        deadline = time.time() + timeout
        while True:
            m = rx.search(self.buf)
            if m:
                text = self.buf[: m.end()]
                self.buf = self.buf[m.end():]
                return text
            if time.time() > deadline or self.closed:
                raise TimeoutError(f"{self.name}: no {pattern!r} within {timeout}s; got {self.buf[-400:]!r}")
            self._pump()

    def drain(self, quiet: float = 1.0, limit: float = 15.0) -> str:
        end = time.time() + limit
        last = time.time()
        while time.time() < end:
            if self._pump():
                last = time.time()
            elif time.time() - last > quiet or self.closed:
                break
        text, self.buf = self.buf, ""
        return text

    def cmd(self, line: str, quiet: float = 1.5, limit: float = 20.0) -> str:
        if self.closed:
            raise ConnectionError(f"{self.name}: connection closed")
        self.drain(0.3, 3)
        self.send(line)
        return self.drain(quiet, limit)


def now():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xrouter-tag", default="505o-amd64")
    ap.add_argument("--image", default="tnc2-emu:dev")
    ap.add_argument("--out", default=None)
    ap.add_argument("--keep", action="store_true", help="leave containers running")
    ap.add_argument("--tn-console", type=int, default=18102)
    ap.add_argument("--xr-telnet", type=int, default=18123)
    a = ap.parse_args()

    out = a.out or os.path.join("evidence", f"xrouter-{a.xrouter_tag}-{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}")
    os.makedirs(out, exist_ok=True)
    out = os.path.abspath(out)
    tag = a.xrouter_tag.replace(".", "-")
    tn_name = f"tnc2-thenet-{tag}"
    xr_name = f"tnc2-xrouter-{tag}"
    xr_vol = f"tnc2-xrouter-data-{tag}"
    tn_vol = f"tnc2-thenet-data-{tag}"
    cfgdir = os.path.join(out, "xrouter-config")
    os.makedirs(cfgdir, exist_ok=True)
    with open(os.path.join(cfgdir, "XROUTER.CFG"), "w") as f:
        f.write(XROUTER_CFG)
    with open(os.path.join(cfgdir, "ACCESS.SYS"), "w") as f:
        f.write(ACCESS_SYS)

    results = []

    def check(name, ok, detail=""):
        results.append((name, ok, detail))
        print(f"{'PASS' if ok else 'FAIL'}: {name} {detail}", flush=True)

    def wire():
        """The emulator's decoded radio log so far."""
        r = sh("docker", "logs", tn_name, check=False, capture=True)
        return r.stdout + r.stderr

    def wire_count(pattern):
        return len(re.findall(pattern, wire()))

    def cleanup():
        for c in (tn_name, xr_name):
            sh("docker", "rm", "-f", c, check=False, capture=True)
        for v in (xr_vol, tn_vol):
            sh("docker", "volume", "rm", v, check=False, capture=True)

    cleanup()
    if sh("docker", "network", "inspect", NET, check=False, capture=True).returncode != 0:
        sh("docker", "network", "create", "--subnet", SUBNET, NET)

    print(f"starting {tn_name} ({a.image}) and {xr_name} (xrouter:{a.xrouter_tag}); output in {out}", flush=True)
    sh("docker", "run", "-d", "--name", tn_name, "--network", NET, "--ip", TN_IP,
       "-v", f"{tn_vol}:/data",
       "-e", f"TNC2_CALL={TN_CALL}", "-e", f"TNC2_ALIAS={TN_ALIAS}",
       # radio port quality 192 (PARMS 3) and NODES broadcasts every 60 s (PARMS 7)
       "-e", "TNC2_POKE=4C=C0,00;54=3C,00",
       "-e", "TNC2_CAPTURE=/data/capture.txt",
       "-e", f"TNC2_DEBUG={os.environ.get('TNC2_DEBUG', '0')}",
       "-p", f"127.0.0.1:{a.tn_console}:8002",
       a.image, capture=True)
    time.sleep(2)
    sh("docker", "run", "-d", "--name", xr_name, "--network", NET, "--ip", XR_IP,
       "--cap-add", "NET_RAW",
       "-v", f"{xr_vol}:/data",
       "-v", f"{cfgdir}/XROUTER.CFG:/data/XROUTER.CFG:ro",
       "-v", f"{cfgdir}/ACCESS.SYS:/data/ACCESS.SYS:ro",
       "-p", f"127.0.0.1:{a.xr_telnet}:23",
       f"ghcr.io/packethacking/xrouter:{a.xrouter_tag}", capture=True)

    tn_log = open(os.path.join(out, "thenet-console.txt"), "w")
    xr_log = open(os.path.join(out, "xrouter-console.txt"), "w")
    try:
        # 1. TheNet console
        tn = Console("thenet", "127.0.0.1", a.tn_console, tn_log)
        time.sleep(1)
        tn.send_raw(b"\x1b", "ESC")
        tn.expect(r"\* ", 10)
        tn.send("C")
        signon = tn.expect(r"CONNECTED to .*", 10)
        check("TheNet console connects", True, signon.strip().splitlines()[-1])
        parms = tn.cmd("PARMS")
        fields = parms.split("}", 1)[-1].split()
        check("TheNet PARMS answers", len(fields) > 7 and fields[2] == "192" and fields[6] == "60",
              "(radio quality 192 and broadcast interval 60 s, as patched)")
        tn.cmd("MODE")
        tn.cmd("NODES")
        tn.cmd("ROUTES")

        # XRouter console. XRouter drops the telnet user when a downlink
        # ends, so each connect test gets a fresh login.
        def xr_login():
            c = Console("xrouter", "127.0.0.1", a.xr_telnet, xr_log)
            xr_log.write(f"\n[{now()} new telnet session]\n")
            c.expect(r"(callsign|login|user).*:", 30)
            c.send(LOGIN_CALL)
            c.expect(r"\S", 15)
            c.drain()
            return c

        def tn_leave(line):
            # Leave the far node and wait for TheNet to say the session has
            # ended. A quiet console is not enough: the far node can take
            # longer to disconnect than the quiet window, and the next
            # command would then go into the old session.
            r = tn.cmd(line, quiet=5, limit=40)
            if not re.search(r"Welcome back", r, re.I):
                try:
                    tn.expect(r"Welcome back", 30)
                except TimeoutError:
                    tn_log.write(f"\n[{now()} no 'Welcome back' after {line}]\n")

        def tn_relogin():
            tn_log.write(f"\n[{now()} back to the TheNet node prompt]\n")
            tn.drain(2, 10)
            tn.send_raw(b"\x1b", "ESC")
            tn.drain(2, 5)
            tn.send("C")
            tn.drain(2, 10)

        xr = xr_login()
        xr.cmd("VERSION")
        xr.cmd("PORTS")

        # 2-4. wait for the NODES exchange
        deadline = time.time() + 300
        xr_has_tn = tn_has_xr = xr_route = False
        while time.time() < deadline and not (xr_has_tn and tn_has_xr and xr_route):
            time.sleep(20)
            r = xr.cmd("ROUTES")
            xr_route = TN_CALL in r
            n = xr.cmd("NODES")
            xr_has_tn = TN_ALIAS in n and TN_CALL in n
            t = tn.cmd("NODES")
            tn_has_xr = XR_ALIAS in t or XR_CALL in t
        check("XRouter lists TheNet as a neighbour (ROUTES)", xr_route)
        check("XRouter lists TheNet as a node (NODES)", xr_has_tn)
        check("TheNet lists XRouter in NODES", tn_has_xr)
        tn.cmd("ROUTES")
        xr.cmd(f"NODES {TN_ALIAS}")
        xr.cmd("LINKS")

        # 5. AX.25 level 2 connect from XRouter to TheNet's callsign
        r = xr.cmd(f"C 1 !{TN_CALL}", quiet=4, limit=60)
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = xr.cmd("NODES", quiet=4, limit=60)
            prompt = f"{TN_ALIAS}:{TN_CALL}}}"
            check("L2 connect XRouter -> TheNet callsign gets TheNet prompt", prompt in r2, f"looked for '{prompt}'")
            xr.cmd("BYE", quiet=4, limit=30)
        else:
            check("L2 connect XRouter -> TheNet callsign gets TheNet prompt", False, "no connect")
            xr.drain(3, 30)
        xr = xr_login()

        # 6. NET/ROM connect from XRouter to TheNet's alias. Without TheNet in
        # its node table XRouter would just try a level 2 connect to the
        # alias, so the wire log must show a NET/ROM CONN REQ and CONN ACK.
        creq = rf"RX {XR_CALL}>{TN_CALL} <I.. C> pid=CF len=\d+ NET/ROM {XR_CALL}>{TN_CALL} ttl=\d+ CONN REQ"
        cack = rf"TX {TN_CALL}>{XR_CALL} <I.. C> pid=CF len=\d+ NET/ROM {TN_CALL}>{XR_CALL} ttl=\d+ CONN ACK"
        n_req, n_ack = wire_count(creq), wire_count(cack)
        r = xr.cmd(f"C {TN_ALIAS}", quiet=5, limit=90)
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = xr.cmd("ROUTES", quiet=5, limit=60)
            prompt = f"{TN_ALIAS}:{TN_CALL}}}"
            on_wire = wire_count(creq) > n_req and wire_count(cack) > n_ack
            check("NET/ROM connect XRouter -> TheNet alias", prompt in r2 and on_wire,
                  f"prompt '{prompt}': {prompt in r2}, CONN REQ/ACK on the wire: {on_wire}")
            xr.cmd("BYE", quiet=5, limit=40)
        else:
            check("NET/ROM connect XRouter -> TheNet alias", False, "no connect")
            xr.drain(3, 30)
        xr = xr_login()

        # 7. NET/ROM connect from TheNet's console to XRouter
        treq = rf"TX {TN_CALL}>{XR_CALL} <I.. C> pid=CF len=\d+ NET/ROM {TN_CALL}>{XR_CALL} ttl=\d+ CONN REQ"
        tack = rf"RX {XR_CALL}>{TN_CALL} <I.. C> pid=CF len=\d+ NET/ROM {XR_CALL}>{TN_CALL} ttl=\d+ CONN ACK"
        n_req, n_ack = wire_count(treq), wire_count(tack)
        r = tn.cmd(f"C {XR_ALIAS}", quiet=5, limit=90)
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = tn.cmd("NODES", quiet=5, limit=60)
            on_wire = wire_count(treq) > n_req and wire_count(tack) > n_ack
            got = f"{XR_CALL}:{XR_ALIAS}}}" in r2
            check("NET/ROM connect TheNet -> XRouter alias", got and on_wire,
                  f"XRouter prompt: {got}, CONN REQ/ACK on the wire: {on_wire}")
            tn_leave("BYE")
        else:
            check("NET/ROM connect TheNet -> XRouter alias", False, "no connect")
            tn.drain(3, 30)
        tn_relogin()

        # 8. level 2 downlink from TheNet to XRouter's PMS callsign
        ua = rf"RX {XR_PMSCALL}>{TN_CALL[:-2]}-14 <UA R F>"
        n_ua = wire_count(ua)
        r = tn.cmd(f"C {XR_PMSCALL}", quiet=8, limit=90)
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = tn.cmd("?", quiet=5, limit=60)
            on_wire = wire_count(ua) > n_ua
            check("L2 downlink TheNet -> XRouter PMS callsign", on_wire and len(r2.strip()) > 0,
                  f"UA from {XR_PMSCALL} on the wire: {on_wire}, PMS answered: {len(r2.strip()) > 0}")
            tn_leave("B")
        else:
            check("L2 downlink TheNet -> XRouter PMS callsign", False, "no connect")
            tn.drain(3, 30)
        tn_relogin()

        tn.cmd("NODES")
        tn.cmd("ROUTES")
        tn.cmd("STATS")
        tn.cmd("LINKS")
        xr.cmd("NODES")
        xr.cmd("ROUTES")
    except Exception as e:  # keep going so the logs are saved
        check("run completed", False, repr(e))
    finally:
        tn_log.close()
        xr_log.close()
        with open(os.path.join(out, "thenet-emulator.log"), "w") as f:
            f.write(sh("docker", "logs", tn_name, check=False, capture=True).stderr)
            f.write(sh("docker", "logs", tn_name, check=False, capture=True).stdout)
        with open(os.path.join(out, "xrouter-docker.log"), "w") as f:
            r = sh("docker", "logs", xr_name, check=False, capture=True)
            f.write(r.stdout + r.stderr)
        sh("docker", "cp", f"{tn_name}:/data/capture.txt", os.path.join(out, "radio-capture.txt"), check=False, capture=True)
        sh("docker", "cp", f"{xr_name}:/data/LOG", os.path.join(out, "xrouter-LOG"), check=False, capture=True)
        with open(os.path.join(out, "results.txt"), "w") as f:
            f.write(f"XRouter image ghcr.io/packethacking/xrouter:{a.xrouter_tag}, emulator image {a.image}, run at {now()}\n")
            for name, ok, detail in results:
                f.write(f"{'PASS' if ok else 'FAIL'}: {name} {detail}\n")
        if not a.keep:
            cleanup()
    failed = [r for r in results if not r[1]]
    print(f"{len(results) - len(failed)} passed, {len(failed)} failed; evidence in {out}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
