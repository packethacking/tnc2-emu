#!/usr/bin/env python3
"""LinBPQ <-> TheNet X1J interop run.

The LinBPQ counterpart of run.py. Starts the tnc2-emu container (TheNet
X1J) and a LinBPQ container on a private docker network, with LinBPQ
dialling the emulator's KISS port as a TCP KISS port. Then it drives both
consoles through the checks below and saves raw transcripts and logs under
the output directory.

  1. TheNet signs on, PARMS / MODE / NODES / ROUTES answer.
  2. LinBPQ lists TheNet as a neighbour (ROUTES) and a node (NODES).
  3. TheNet lists LinBPQ in NODES.
  4. LinBPQ's node link to TheNet comes up (SABM answered by UA).
  5. AX.25 level 2 connect from LinBPQ to TheNet's callsign gets the
     TheNet prompt.
  6. NET/ROM connect from LinBPQ to TheNet's alias works.
  7. NET/ROM connect from TheNet's console to LinBPQ works.
  8. Level 2 downlink from TheNet's console to LinBPQ's port callsign.

LinBPQ opens node links with an AX.25 2.2 XID frame, which TheNet ignores,
and gives up on the neighbour when it hears nothing back. The ROUTES entry
with NOV2.2=1 below makes it send a plain SABM instead. --without-nov22
leaves that entry out, to show what goes wrong without it.

Usage: interop/run_linbpq.py [--linbpq-tag latest] [--image tnc2-emu:dev] [--out DIR]

Containers, network and volumes are all named tnc2-*, and only those are
removed at the end.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import time

from run import Console, now, sh

NET = "tnc2-bpq-net"
SUBNET = "172.29.76.0/24"
TN_IP = "172.29.76.10"
BPQ_IP = "172.29.76.12"

TN_CALL, TN_ALIAS = "G9TNT-1", "TNET"
BPQ_CALL, BPQ_ALIAS = "G9BPQ", "BPQNOD"
BPQ_USER, BPQ_PASS = "sysop", "changeme"
# The telnet user's callsign. It must differ from NODECALL, so that a level
# 2 connect to TheNet does not clash with LinBPQ's own node link.
LOGIN_CALL = "G9ABC"
# A callsign on LinBPQ's KISS port that is not in NODES, so TheNet has to
# reach it with a plain level 2 downlink.
BPQ_PORTCALL = "G9BPQ-2"


def bpq32_cfg(nov22: bool) -> str:
    cfg = f"""; LinBPQ side of the TheNet X1J interop run (generated by interop/run_linbpq.py).
SIMPLE=1
NODECALL={BPQ_CALL}
NODEALIAS={BPQ_ALIAS}
LOCATOR=IO91WL
NODESINTERVAL=1

PORT
 ID=Telnet
 DRIVER=Telnet
 CONFIG
 TCPPORT=8010
 MAXSESSIONS=10
 USER={BPQ_USER},{BPQ_PASS},{LOGIN_CALL},,SYSOP
ENDPORT

; The TNC-2 emulator's radio port, as KISS over TCP. LinBPQ is the client.
PORT
 ID=TheNet TNC2
 TYPE=ASYNC
 PROTOCOL=KISS
 IPADDR={TN_IP}
 TCPPORT=8001
 PORTCALL={BPQ_PORTCALL}
 QUALITY=192
 MAXFRAME=2
 PACLEN=120
 FRACK=8000
 RESPTIME=1500
 RETRIES=10
ENDPORT
"""
    if nov22:
        cfg += f"""
; TheNet ignores XID, so talk AX.25 2.0 (plain SABM) to it.
ROUTES:
CALL={TN_CALL},PORT=2,QUALITY=192,NOV2.2=1
***
"""
    return cfg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--linbpq-tag", default="latest")
    ap.add_argument("--image", default="tnc2-emu:dev")
    ap.add_argument("--out", default=None)
    ap.add_argument("--keep", action="store_true", help="leave containers running")
    ap.add_argument("--without-nov22", action="store_true", help="leave out the NOV2.2 ROUTES entry")
    ap.add_argument("--tn-console", type=int, default=18202)
    ap.add_argument("--bpq-telnet", type=int, default=18210)
    a = ap.parse_args()
    nov22 = not a.without_nov22

    suffix = "" if nov22 else "-without-nov22"
    out = a.out or os.path.join("evidence", f"linbpq-{a.linbpq_tag}{suffix}-{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}")
    os.makedirs(out, exist_ok=True)
    out = os.path.abspath(out)
    tn_name, bpq_name = "tnc2-bpq-thenet", "tnc2-bpq-linbpq"
    tn_vol, bpq_vol = "tnc2-bpq-thenet-data", "tnc2-bpq-linbpq-data"
    cfgdir = os.path.join(out, "linbpq-config")
    os.makedirs(cfgdir, exist_ok=True)
    with open(os.path.join(cfgdir, "bpq32.cfg"), "w") as f:
        f.write(bpq32_cfg(nov22))

    bpq_image = f"m0lte/linbpq:{a.linbpq_tag}"
    results = []

    def check(name, ok, detail=""):
        results.append((name, ok, detail))
        print(f"{'PASS' if ok else 'FAIL'}: {name} {detail}", flush=True)

    def wire():
        """The emulator's decoded radio log so far."""
        r = sh("docker", "logs", tn_name, check=False, capture=True)
        return r.stdout + r.stderr

    def wire_count(pattern):
        return len(re.findall(pattern, wire()))

    def connect(c, line, limit=150.0):
        """Send a connect command and read until it succeeds or fails."""
        c.drain(0.3, 3)
        c.send(line)
        try:
            text = c.expect(r"connected to|failure|busy|sorry|disappeared|not (?:in|known)|invalid|needs port", limit)
        except TimeoutError:
            text = c.buf
            c.buf = ""
        return text + c.drain(3, 15)

    def cleanup():
        for c in (tn_name, bpq_name):
            sh("docker", "rm", "-f", c, check=False, capture=True)
        for v in (tn_vol, bpq_vol):
            sh("docker", "volume", "rm", v, check=False, capture=True)

    cleanup()
    if sh("docker", "network", "inspect", NET, check=False, capture=True).returncode != 0:
        sh("docker", "network", "create", "--subnet", SUBNET, NET)

    bpq_version = sh("docker", "image", "inspect", bpq_image, "--format",
                     '{{index .Config.Labels "org.opencontainers.image.version"}}',
                     check=False, capture=True).stdout.strip()
    print(f"starting {tn_name} ({a.image}) and {bpq_name} ({bpq_image}, {bpq_version}); "
          f"NOV2.2 {'on' if nov22 else 'off'}; output in {out}", flush=True)
    sh("docker", "run", "-d", "--name", tn_name, "--network", NET, "--ip", TN_IP,
       "-v", f"{tn_vol}:/data",
       "-e", f"TNC2_CALL={TN_CALL}", "-e", f"TNC2_ALIAS={TN_ALIAS}",
       # radio port quality 192 (PARMS 3) and NODES broadcasts every 60 s (PARMS 7)
       "-e", "TNC2_POKE=4C=C0,00;54=3C,00",
       "-e", "TNC2_CAPTURE=/data/capture.txt",
       "-p", f"127.0.0.1:{a.tn_console}:8002",
       a.image, capture=True)
    time.sleep(2)
    sh("docker", "run", "-d", "--name", bpq_name, "--network", NET, "--ip", BPQ_IP,
       "-v", f"{bpq_vol}:/data",
       "-v", f"{cfgdir}/bpq32.cfg:/data/bpq32.cfg:ro",
       "-p", f"127.0.0.1:{a.bpq_telnet}:8010",
       bpq_image, capture=True)

    tn_log = open(os.path.join(out, "thenet-console.txt"), "w")
    bpq_log = open(os.path.join(out, "linbpq-console.txt"), "w")
    try:
        # 1. TheNet console
        tn = Console("thenet", "127.0.0.1", a.tn_console, tn_log)
        time.sleep(1)
        tn.send_raw(b"\x1b", "ESC")
        tn.expect(r"\* ", 10)
        tn.send("C")
        signon = tn.expect(r"CONNECTED to .*", 10)
        check("TheNet console connects", True, signon.strip().splitlines()[-1])
        parms = tn.cmd("PARMS")
        fields = parms.split("}", 1)[-1].split()
        check("TheNet PARMS answers", len(fields) > 7 and fields[2] == "192" and fields[6] == "60",
              "(radio quality 192 and broadcast interval 60 s, as patched)")
        tn.cmd("MODE")
        tn.cmd("NODES")
        tn.cmd("ROUTES")

        # LinBPQ telnet. Each connect test gets a fresh login, so a
        # downlink that ends the session cannot spoil the next test.
        def bpq_login():
            c = Console("linbpq", "127.0.0.1", a.bpq_telnet, bpq_log)
            bpq_log.write(f"\n[{now()} new telnet session]\n")
            c.expect(r"user:", 30)
            c.send(BPQ_USER)
            c.expect(r"password:", 15)
            c.send(BPQ_PASS)
            c.expect(r"Connected to .*Telnet Server", 15)
            c.drain()
            return c

        def bpq_relogin(c):
            try:
                c.sock.close()
            except OSError:
                pass
            return bpq_login()

        def tn_leave(line):
            # Leave the far node and wait for TheNet to say the session has
            # ended. A quiet console is not enough: the far node can take
            # longer to disconnect than the quiet window, and the next
            # command would then go into the old session.
            r = tn.cmd(line, quiet=5, limit=40)
            if not re.search(r"Welcome back", r, re.I):
                try:
                    tn.expect(r"Welcome back", 30)
                except TimeoutError:
                    tn_log.write(f"\n[{now()} no 'Welcome back' after {line}]\n")

        def tn_relogin():
            tn_log.write(f"\n[{now()} back to the TheNet node prompt]\n")
            tn.drain(2, 10)
            tn.send_raw(b"\x1b", "ESC")
            tn.drain(2, 5)
            tn.send("C")
            tn.drain(2, 10)

        bpq = bpq_login()
        bpq.cmd("VERSION")
        bpq.cmd("PORTS")

        # 2-4. wait for the NODES exchange and LinBPQ's node link. The
        # ROUTES entry is in bpq32.cfg, so the neighbour only counts once
        # it has a node behind it. The link must be up (S=5) in LINKS and
        # TheNet must have answered LinBPQ's SABM with a UA; while LinBPQ
        # is still sending XIDs, LINKS shows the link at S=1.
        link_ua = rf"TX {TN_CALL}>{BPQ_CALL} <UA R F>"
        xid = rf"RX {BPQ_CALL}>{TN_CALL} <U\?bf C P>"
        deadline = time.time() + 300
        bpq_has_tn = tn_has_bpq = bpq_route = link_up = False
        while time.time() < deadline and not (bpq_has_tn and tn_has_bpq and bpq_route and link_up):
            time.sleep(20)
            r = bpq.cmd("ROUTES")
            bpq_route = re.search(rf"\b2\s+{TN_CALL}\s+\d+\s+[1-9]", r) is not None
            n = bpq.cmd("NODES")
            bpq_has_tn = TN_ALIAS in n and TN_CALL in n
            t = tn.cmd("NODES")
            tn_has_bpq = BPQ_ALIAS in t or BPQ_CALL in t
            links = bpq.cmd("LINKS")
            link_up = re.search(rf"^{TN_CALL}\s+{BPQ_CALL}\s+S=5", links, re.M) is not None and wire_count(link_ua) > 0
        check("LinBPQ lists TheNet as a neighbour with a node behind it (ROUTES)", bpq_route)
        check("LinBPQ lists TheNet as a node (NODES)", bpq_has_tn)
        check("TheNet lists LinBPQ in NODES", tn_has_bpq)
        check("LinBPQ node link to TheNet comes up", link_up,
              f"XID frames sent to TheNet: {wire_count(xid)}, UA from TheNet: {wire_count(link_ua)}")
        tn.cmd("ROUTES")
        bpq.cmd(f"NODES {TN_ALIAS}")

        # 5. AX.25 level 2 connect from LinBPQ to TheNet's callsign. Without
        # the "!" LinBPQ would connect over NET/ROM, as TheNet is in NODES, so
        # the wire log must show a SABM from the telnet user's callsign.
        sabm = rf"RX {LOGIN_CALL}(-\d+)?>{TN_CALL} <SABM C P>"
        n_sabm = wire_count(sabm)
        r = connect(bpq, f"C 2 !{TN_CALL}")
        ok = re.search(r"connected to", r, re.I) is not None
        prompt = f"{TN_ALIAS}:{TN_CALL}}}"
        if ok:
            r2 = bpq.cmd("NODES", quiet=4, limit=60)
            on_wire = wire_count(sabm) > n_sabm
            check("L2 connect LinBPQ -> TheNet callsign gets TheNet prompt", prompt in r2 and on_wire,
                  f"prompt '{prompt}': {prompt in r2}, SABM from {LOGIN_CALL} on the wire: {on_wire}")
            bpq.cmd("BYE", quiet=4, limit=30)
        else:
            check("L2 connect LinBPQ -> TheNet callsign gets TheNet prompt", False, f"no connect: {r.strip()[-120:]!r}")
            bpq.drain(3, 30)
        bpq = bpq_relogin(bpq)

        # 6. NET/ROM connect from LinBPQ to TheNet's alias. LinBPQ answers
        # "needs port number" when the alias is not in its node table, so
        # the wire log must show a NET/ROM CONN REQ and CONN ACK.
        creq = rf"RX {BPQ_CALL}>{TN_CALL} <I.. C(?: P)?> pid=CF len=\d+ NET/ROM {BPQ_CALL}>{TN_CALL} ttl=\d+ CONN REQ"
        cack = rf"TX {TN_CALL}>{BPQ_CALL} <I.. C(?: P)?> pid=CF len=\d+ NET/ROM {TN_CALL}>{BPQ_CALL} ttl=\d+ CONN ACK"
        n_req, n_ack = wire_count(creq), wire_count(cack)
        r = connect(bpq, f"C {TN_ALIAS}")
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = bpq.cmd("ROUTES", quiet=5, limit=60)
            on_wire = wire_count(creq) > n_req and wire_count(cack) > n_ack
            check("NET/ROM connect LinBPQ -> TheNet alias", prompt in r2 and on_wire,
                  f"prompt '{prompt}': {prompt in r2}, CONN REQ/ACK on the wire: {on_wire}")
            bpq.cmd("BYE", quiet=5, limit=40)
        else:
            check("NET/ROM connect LinBPQ -> TheNet alias", False, f"no connect: {r.strip()[-120:]!r}")
            bpq.drain(3, 30)
        bpq = bpq_relogin(bpq)

        # 7. NET/ROM connect from TheNet's console to LinBPQ
        treq = rf"TX {TN_CALL}>{BPQ_CALL} <I.. C(?: P)?> pid=CF len=\d+ NET/ROM {TN_CALL}>{BPQ_CALL} ttl=\d+ CONN REQ"
        tack = rf"RX {BPQ_CALL}>{TN_CALL} <I.. C(?: P)?> pid=CF len=\d+ NET/ROM {BPQ_CALL}>{TN_CALL} ttl=\d+ CONN ACK"
        n_req, n_ack = wire_count(treq), wire_count(tack)
        r = connect(tn, f"C {BPQ_ALIAS}")
        ok = re.search(r"connected to", r, re.I) is not None
        bpq_prompt = f"{BPQ_ALIAS}:{BPQ_CALL}}}"
        if ok:
            r2 = tn.cmd("NODES", quiet=5, limit=60)
            on_wire = wire_count(treq) > n_req and wire_count(tack) > n_ack
            got = bpq_prompt in r2
            check("NET/ROM connect TheNet -> LinBPQ alias", got and on_wire,
                  f"LinBPQ prompt: {got}, CONN REQ/ACK on the wire: {on_wire}")
            tn_leave("BYE")
        else:
            check("NET/ROM connect TheNet -> LinBPQ alias", False, "no connect")
            tn.drain(3, 30)
        tn_relogin()

        # 8. level 2 downlink from TheNet to LinBPQ's port callsign. TheNet
        # makes downlinks from its callsign with the SSID turned round (15-n).
        ua = rf"RX {BPQ_PORTCALL}>{TN_CALL[:-2]}-14 <UA R F>"
        n_ua = wire_count(ua)
        r = connect(tn, f"C {BPQ_PORTCALL}")
        ok = re.search(r"connected to", r, re.I) is not None
        if ok:
            r2 = tn.cmd("PORTS", quiet=5, limit=60)
            on_wire = wire_count(ua) > n_ua
            got = bpq_prompt in r2
            check("L2 downlink TheNet -> LinBPQ port callsign", on_wire and got,
                  f"UA from {BPQ_PORTCALL} on the wire: {on_wire}, LinBPQ prompt: {got}")
            tn_leave("BYE")
        else:
            check("L2 downlink TheNet -> LinBPQ port callsign", False, "no connect")
            tn.drain(3, 30)
        tn_relogin()

        tn.cmd("NODES")
        tn.cmd("ROUTES")
        tn.cmd("STATS")
        tn.cmd("LINKS")
        bpq.cmd("NODES")
        bpq.cmd("ROUTES")
        bpq.cmd("LINKS")
    except Exception as e:  # keep going so the logs are saved
        check("run completed", False, repr(e))
    finally:
        tn_log.close()
        bpq_log.close()
        with open(os.path.join(out, "thenet-emulator.log"), "w") as f:
            r = sh("docker", "logs", tn_name, check=False, capture=True)
            f.write(r.stderr + r.stdout)
        with open(os.path.join(out, "linbpq-docker.log"), "w") as f:
            r = sh("docker", "logs", bpq_name, check=False, capture=True)
            f.write(r.stdout + r.stderr)
        sh("docker", "cp", f"{tn_name}:/data/capture.txt", os.path.join(out, "radio-capture.txt"), check=False, capture=True)
        with open(os.path.join(out, "results.txt"), "w") as f:
            f.write(f"LinBPQ image {bpq_image} ({bpq_version}), NOV2.2 route {'on' if nov22 else 'off'}, "
                    f"emulator image {a.image}, run at {now()}\n")
            for name, ok, detail in results:
                f.write(f"{'PASS' if ok else 'FAIL'}: {name} {detail}\n")
        if not a.keep:
            cleanup()
    failed = [r for r in results if not r[1]]
    print(f"{len(results) - len(failed)} passed, {len(failed)} failed; evidence in {out}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
